// Renders the trace's results as Markdown, one report per question, each row
// with the file:line it rests on.

const code = (s) => `\`${s}\``;
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
function table(head, rows) {
	return [
		`| ${head.join(" | ")} |`,
		`|${head.map(() => "---").join("|")}|`,
		...rows.map((r) => `| ${r.map(cell).join(" | ")} |`),
	].join("\n");
}
const isNew = (f) => (f.new ? " **new**" : "");

function header(title, meta, intro) {
	return [
		`# ${title}`,
		"",
		`Generated by \`npm run trace\` at ${meta.time} from commit \`${meta.commit}\`. ${intro}`,
		"",
	].join("\n");
}

function findingList(findings) {
	if (findings.length === 0) return ["None.", ""];
	return [
		...findings.flatMap((f) => [
			`- ${f.text}${f.where.length && !f.lacks ? ` (${f.where.map(code).join(", ")})` : ""}${isNew(f)}`,
			...(f.lacks ?? []).map(
				(g) =>
					`  - ${g.entryPoint} (${code(g.where)}) does not reach: ${g.writes.map(code).join(", ")}`,
			),
		]),
		"",
	];
}

export function renderOperations(meta, operations, findings) {
	const parts = [
		header(
			"Operations as built",
			meta,
			"For each operation of the catalog: the entry points that serve it, whether each reaches the operation's home, the database writes each reaches, and the calls the call graph could not resolve (where reach may be incomplete). Findings follow each operation.",
		),
	];
	for (const op of operations) {
		const fs = findings.filter(
			(f) => f.about === op.id && f.kind.startsWith("op."),
		);
		parts.push(
			`## ${code(op.id)}${op.planned ? " (planned)" : ""}`,
			"",
			`${op.intent}. Actors: ${op.actors.join(", ")}. Home: ${code(op.home)}.`,
			"",
		);
		if (op.entryPoints.length > 0)
			parts.push(
				table(
					[
						"Entry point",
						"Actor",
						"Where",
						"Reaches home",
						"Writes reached",
						"Via HTTP",
						"Unresolved calls",
					],
					op.entryPoints.map((e) => [
						`${e.kind} ${code(e.name)}`,
						e.actor,
						code(e.where),
						e.reachesHome ? "yes" : "**no**",
						e.writes.length ? e.writes.map(code).join("<br>") : "—",
						e.httpHops.length ? e.httpHops.map(code).join("<br>") : "—",
						e.unresolved.length ? e.unresolved.map(code).join(", ") : "—",
					]),
				),
				"",
			);
		parts.push(...findingList(fs));
	}
	return parts.join("\n");
}

export function renderWrites(meta, writes, findings, b) {
	const parts = [
		header(
			"Database writes",
			meta,
			"Every write to MongoDB in the sources, checked against the data stores (the one component allowed to write each collection) and, for a status, against the entity's allowed transitions.",
		),
		"## Writes by collection",
		"",
	];
	for (const store of b.DATA_STORES) {
		const ws = writes.filter((w) => w.collection === store.collection);
		parts.push(
			`### ${code(store.collection)}`,
			"",
			`Holds ${store.holds}. Owner: ${code(store.owner)}${(store.alsoWrittenBy ?? []).length ? `; also ${store.alsoWrittenBy.map((x) => `${code(x.component)} (${x.what})`).join(", ")}` : ""}.`,
			"",
		);
		if (ws.length === 0) parts.push("No writes found.", "");
		else
			parts.push(
				table(
					["Where", "Function", "Component", "Method", "Owner?", "Status"],
					ws.map((w) => [
						code(`${w.file}:${w.line}`),
						code(w.function),
						code(w.component),
						w.method,
						w.ownerOk ? "yes" : "**no**",
						w.statusCheck
							? `${w.statusCheck.from.map((v) => (v === "∅" ? "(new)" : v)).join("\\|")} → ${w.statusCheck.to.join("\\|")}${w.statusCheck.undeclared.length ? ` **(${w.statusCheck.undeclared.length} not allowed)**` : ""}`
							: "",
					]),
				),
				"",
			);
	}
	const unknown = writes.filter((w) => !w.collection);
	if (unknown.length > 0)
		parts.push(
			"## Writes whose collection could not be determined",
			"",
			...unknown.map(
				(w) =>
					`- ${code(`${w.file}:${w.line}`)} ${w.method} in ${code(w.function)}`,
			),
			"",
		);
	for (const [kind, title] of [
		[
			"store.foreign-writer",
			"Writes by a component that does not own the collection",
		],
		[
			"status.undeclared-transition",
			"Status changes the catalog does not allow",
		],
		["status.unknown-state", "Status values the catalog does not know"],
		["status.unseen-transition", "Allowed transitions no code makes"],
	])
		parts.push(
			`## ${title}`,
			"",
			...findingList(findings.filter((f) => f.kind === kind)),
		);
	return parts.join("\n");
}

export function renderSecurity(meta, security, invariants, ran) {
	const parts = [
		header(
			"Security",
			meta,
			"CodeQL's standard security queries (`javascript-security-extended`), each result filed under the security invariant it bears on.",
		),
	];
	if (!ran) {
		parts.push("The security suite was not run (`--no-security`).", "");
		return parts.join("\n");
	}
	const sec = invariants.filter((i) => i.scope === "security");
	parts.push(
		table(
			["Invariant", "Results", "Enforced by"],
			[...sec, { id: "sec.unmapped", enforcedBy: [] }].map((i) => [
				code(i.id),
				security.filter((s) => s.invariant === i.id).length,
				i.enforcedBy?.length
					? i.enforcedBy.map((e) => e.kind).join(", ")
					: "nothing yet",
			]),
		),
		"",
	);
	for (const i of [...sec.map((x) => x.id), "sec.unmapped"]) {
		const rows = security.filter((s) => s.invariant === i);
		if (rows.length === 0) continue;
		parts.push(
			`## ${code(i)}`,
			"",
			table(
				["Rule", "Where", "Component", "Message"],
				rows.map((r) => [
					code(r.rule),
					code(`${r.file}:${r.line}`),
					code(r.component),
					r.message.split("\n")[0].slice(0, 200),
				]),
			),
			"",
		);
	}
	return parts.join("\n");
}

export function renderInvariants(meta, invariants) {
	return [
		header(
			"Invariants",
			meta,
			"Every invariant of the catalog: what enforces it, the ADR that chose it, any open decision, and how many findings of this run bear on it.",
		),
		table(
			[
				"Invariant",
				"Scope",
				"Enforced by",
				"Decided in",
				"Open decision",
				"Findings",
			],
			invariants.map((i) => [
				code(i.id),
				i.scope,
				i.enforcedBy.length
					? i.enforcedBy.map((e) => e.kind).join(", ")
					: "**nothing yet**",
				i.decidedBy ?? "",
				i.open ?? "",
				i.findings,
			]),
		),
		"",
	].join("\n");
}

export function renderIndex(meta, counts, findings, previousRan) {
	const kinds = [...new Set(findings.map((f) => f.kind))].sort();
	return [
		header(
			"Trace",
			meta,
			"What the code does, joined to what the catalog says it should do. Reports in this folder; `todo.json` lists every finding with a stable key.",
		),
		table(
			["Measure", "Count"],
			Object.entries(counts).map(([k, v]) => [k, v]),
		),
		"",
		"## Findings",
		"",
		table(
			[
				"Kind",
				"Findings",
				previousRan ? "New since the last run" : "New (no previous run)",
			],
			kinds.map((k) => {
				const fs = findings.filter((f) => f.kind === k);
				return [
					code(k),
					fs.length,
					previousRan ? fs.filter((f) => f.new).length : "—",
				];
			}),
		),
		"",
		"## Reports",
		"",
		"- [operations.md](operations.md): each operation's entry points, what they reach, how they differ",
		"- [writes.md](writes.md): every database write, its owner and the status changes it can make",
		"- [security.md](security.md): CodeQL's security results, by security invariant",
		"- [invariants.md](invariants.md): every invariant and what enforces it",
		"- [components.html](components.html): the component map, from the imports in the code",
		"",
	].join("\n");
}
